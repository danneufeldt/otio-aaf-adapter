"""
Create Avid "Motion Control" time warp effects when writing AAF.

The AAF reader already captures a Motion Control time warp losslessly
onto the corresponding OTIO effects metadata["AAF"] using
advanced_authoring_format._transcribe_operation_group() and _transcribe_property().

This includes the constant parameters:
    SpeedRatio
    AvidMotionPulldown
and the time sampled properties
    PARAM_SPEED_MAP_U
    PARAM_SPEED_OFFSET_MAP_U
as well as the control points and interpolation settings for the hand authored
curves created in the timewarp tool.

The current goal for this module is to allow a lossless round trip of that information
back into a generated AAF, with a future goal of allowing direct authoring of timewarps
when creating timelines from scratch using OTIO without a reference AAF to base them on.

This is done by reconstructing the OperationGroup using the values in metadata['AAF'].

Because this is fairly complicated and also experimental it's in a separate module
from the primary aaf_writer and is only called once in that class, making it easy to 
disentangle it if needed, or add a runtime switch to disable it.
"""

import collections.abc
import uuid

import aaf2
import aaf2.misc
import aaf2.rational
import opentimelineio as otio

__all__ = ["wrap_input_segment"]

# Avid Motion Control time warp definitions.
# The two speed-map ParameterDefs are not listed in the
# OperationDef's ParametersDefined set, so putting their AUIDs here to be
# able to author them when reconstructing a time warp using the metadata
# in a timeline generated by the AAF -> OTIO pipeline.

# These values were reverse engineered out of a few sample AAFs using pyaaf2
# so it's not clear yet how definitive they are.

# This uuid is also found in pyaaf2/src/aaf2/model/datadefs.py
# as "9d2ea890-0968-11d3-8a38-0050040ef7d2" : ("OperationDef_VideoSpeedControl", "")
AAF_OPERATIONDEF_MOTIONCONTROL = uuid.UUID("9d2ea890-0968-11d3-8a38-0050040ef7d2")


# Speed-graph keyframes (the variable-speed curve and its baked offset map).
AAF_PARAMETERDEF_SPEED_MAP_U = uuid.UUID("8d56827c-847e-11d5-935a-50f857c10000")
AAF_PARAMETERDEF_SPEED_OFFSET_MAP_U = uuid.UUID(
    "8d56827d-847e-11d5-935a-50f857c10000")

# Position-graph keyframes (used by warps authored as an offset/position curve).
AAF_PARAMETERDEF_OFFSET_MAP_U = uuid.UUID("8d56827a-847e-11d5-935a-50f857c10000")
# Scalar Motion Control parameters.

# This uuid is also found in pyaaf2/src/aaf2/model/datadefs.py
# "72559a80-24d7-11d3-8a50-0050040ef7d2" : ("ParameterDef_SpeedRatio", ""),
AAF_PARAMETERDEF_SPEEDRATIO = uuid.UUID("72559a80-24d7-11d3-8a50-0050040ef7d2")

AAF_PARAMETERDEF_AVIDMOTIONINPUTFORMAT = uuid.UUID(
    "1c5a02d5-e503-4ca6-8617-d7914bb8ac03")
AAF_PARAMETERDEF_AVIDMOTIONOUTPUTFORMAT = uuid.UUID(
    "8dde1839-6862-4874-a1e9-4fbd1164f22a")
AAF_PARAMETERDEF_AVIDMOTIONPULLDOWN = uuid.UUID(
    "f7ffed29-fc8e-43ed-943a-4b57b5c157ee")
AAF_PARAMETERDEF_AVIDPHASE = uuid.UUID("5b22ff71-c51b-11d3-a069-006094eb75cb")

MOTION_CONTROL_NAME = "Motion Control"

# Names of the time warp parameters whose values are AAF Rationals. Everything
# else on a Motion Control group is an integer value (so far).
_RATIONAL_PARAMS = frozenset((
    "SpeedRatio",
    "PARAM_SPEED_MAP_U",
    "PARAM_SPEED_OFFSET_MAP_U",
    "PARAM_OFFSET_MAP_U",
))

# AUIDs for the standard Motion Control parameters. Avid does not
# always populate the OperationDef's ``ParametersDefined`` set (the keyframed
# maps are never listed there, and freshly exported AAFs may omit the scalars
# too), so the writer relies on this table rather than the captured metadata.
_KNOWN_PARAM_AUIDS = {
    "PARAM_SPEED_MAP_U": AAF_PARAMETERDEF_SPEED_MAP_U,
    "PARAM_SPEED_OFFSET_MAP_U": AAF_PARAMETERDEF_SPEED_OFFSET_MAP_U,
    "PARAM_OFFSET_MAP_U": AAF_PARAMETERDEF_OFFSET_MAP_U,
    "SpeedRatio": AAF_PARAMETERDEF_SPEEDRATIO,
    "AvidMotionInputFormat": AAF_PARAMETERDEF_AVIDMOTIONINPUTFORMAT,
    "AvidMotionOutputFormat": AAF_PARAMETERDEF_AVIDMOTIONOUTPUTFORMAT,
    "AvidMotionPulldown": AAF_PARAMETERDEF_AVIDMOTIONPULLDOWN,
    "AvidPhase": AAF_PARAMETERDEF_AVIDPHASE,
}

# Reader interpolation names (see ``_PROPERTY_INTERPOLATION_MAP``) -> pyaaf2 AUID.
_INTERPOLATION_NAME_TO_AUID = {
    "Constant": aaf2.misc.ConstantInterp,
    "Linear": aaf2.misc.LinearInterp,
    "Bezier": aaf2.misc.BezierInterpolator,
    "Cubic": aaf2.misc.CubicInterpolator,
}

_INTERPOLATION_AUID_TO_NAME = {
    aaf2.misc.ConstantInterp: "ConstantInterp",
    aaf2.misc.LinearInterp: "LinearInterp",
    aaf2.misc.BezierInterpolator: "BezierInterpolator",
    aaf2.misc.CubicInterpolator: "AvidCubicInterpolator",
}


def _aaf_metadata(otio_object):
    return otio_object.metadata.get("AAF", {}) or {}


def _find_timewarp_effect(otio_clip):
    """Return the Motion Control time warp effect on otio_clip, if any."""
    for effect in getattr(otio_clip, "effects", []):
        if not isinstance(effect, otio.schema.Effect):
            continue
        aaf = _aaf_metadata(effect)
        operation = aaf.get("Operation", {})
        if not operation.get("IsTimeWarp"):
            continue
        if operation.get("Name") != MOTION_CONTROL_NAME:
            continue
        if not aaf.get("Parameters"):
            continue
        return effect
    return None


def _is_keyframed(value):
    return (isinstance(value, collections.abc.Mapping)
            and value.get("_aaf_keyframed_property"))


def _register_def(aaf_file, lookup, create):
    """
    Register or return a definition in aaf_file.dictionary
    The failure case behavior of aaf2.dictionary.lookup_def has the potential
    to vary a little so a couple error handling methods are used here.

    """
    existing = None
    try:
        existing = lookup()
    except KeyError:
        pass
    except Exception as e:
        # aaf2.dictionary.lookup_def raises a plain Exception type
        # so checking the string value of the exception to avoid
        # a blanket catch here.
        if "No Definition" not in str(e):
            raise
    if existing is not None:
        return existing
    new_def = create()
    aaf_file.dictionary.register_def(new_def)
    return new_def


def _interpolation_def(aaf_file, interpolation_name):
    auid = _INTERPOLATION_NAME_TO_AUID.get(
        interpolation_name,
        aaf2.misc.LinearInterp
    )
    name = _INTERPOLATION_AUID_TO_NAME[auid]
    return _register_def(
        aaf_file,
        lambda: aaf_file.dictionary.lookup_interperlationdef(name),# sic
        lambda: aaf_file.create.InterpolationDef(auid, name, name),
    )


def _parameter_def(aaf_file, name, operation):
    """Look up / create the ParameterDef for parameter name."""

    defined = operation.get("ParametersDefined", {}).get(name, {})
    identification = defined.get("Identification")
    # use the existing uuid if present
    if identification:
        auid = uuid.UUID(identification)
    elif name in _KNOWN_PARAM_AUIDS:
        # try to look it up in the dict of known AUIDS
        auid = _KNOWN_PARAM_AUIDS[name]
    else:
        return None

    if name in _RATIONAL_PARAMS:
        typedef = aaf_file.dictionary.lookup_typedef("Rational")
    else:
        typedef = aaf_file.dictionary.lookup_typedef("aafInt32")

    description = defined.get("Description", "")
    return _register_def(
        aaf_file,
        lambda: aaf_file.dictionary.lookup_parameterdef(auid),
        lambda: aaf_file.create.ParameterDef(auid, name, description, typedef),
    )


def _as_rational(value):
    """
        Convert a value expressed in the metadata as a string into an AAFRational.
        AFRational accepts strings, including fractions like 133/120,
        ints/floats and Rationals directly and, for
        floats, picks an int32-safe rational approximation.
    """
    return aaf2.rational.AAFRational(value)


def _build_varying_value(aaf_file, param_def, keyframed):
    """Build a VaryingValue (keyframed map) from captured control points."""
    varying_value = aaf_file.create.VaryingValue()
    varying_value.parameterdef = param_def
    # default to Linear I guess if for some reason it is undefined
    varying_value["Interpolation"].value = _interpolation_def(
        aaf_file, keyframed.get("keyframe_interpolation", "Linear"))

    for time, value in keyframed.get("keyframe_values", []):
        point = aaf_file.create.ControlPoint()
        point["Time"].value = _as_rational(time)
        point["Value"].value = _as_rational(value)
        # In the example AAFs so far Avid stamps every 
        # Motion Control control point with this edit hint.
        # not sure how consistent that will be...
        point["EditHint"].value = "RelativeFixed"
        varying_value["PointList"].append(point)

    return varying_value


def _build_constant_value(aaf_file, param_def, name, value):
    """Build a ConstantValue for a non-keyframed parameter."""
    if name in _RATIONAL_PARAMS:
        coerced = _as_rational(value)
    else:
        coerced = int(value)
    return aaf_file.create.ConstantValue(param_def, coerced)


def _build_operation_def(aaf_file, operation, media_kind):
    if operation.get("Identification"):
        auid = uuid.UUID(operation.get("Identification"))
    else:
        auid = AAF_OPERATIONDEF_MOTIONCONTROL

    name = operation.get("Name", MOTION_CONTROL_NAME)

    def create():
        op_def = aaf_file.create.OperationDef(auid, name)
        op_def.media_kind = media_kind
        op_def["IsTimeWarp"].value = bool(operation.get("IsTimeWarp", True))
        op_def["Bypass"].value = int(operation.get("Bypass", 0))
        op_def["NumberInputs"].value = int(operation.get("NumberInputs", 1))
        op_def["OperationCategory"].value = str(
            operation.get("OperationCategory", "OperationCategory_Effect"))
        op_def["DataDefinition"].value = \
            aaf_file.dictionary.lookup_datadef(str(media_kind))
        description = operation.get("Description")
        if description:
            op_def["Description"].value = str(description)
        return op_def

    return _register_def(
        aaf_file,
        lambda: aaf_file.dictionary.lookup_operationdef(auid),
        create,
    )


def wrap_input_segment(aaf_file, otio_clip, input_segment, media_kind):
    """Wrap input_segment in a Motion Control OperationGroup if needed.

    Args:
        aaf_file: the open aaf2.file.AAFFile file being written.
        otio_clip (otio.schema.Clip): the clip being transcribed.
        input_segment: the AAF segment (e.g. SourceClip) produced for the clip.
        media_kind (str): the track media kind ("Picture" / "Sound").

    Returns:
        A new aaf2.components.OperationGroup wrapping input_segment when
        the clip carries a Motion Control time warp; otherwise input_segment
        unchanged.
    """
    effect = _find_timewarp_effect(otio_clip)
    if effect is None:
        return input_segment

    aaf_md = _aaf_metadata(effect)
    operation = aaf_md.get("Operation", {})
    parameters = aaf_md.get("Parameters", {})

    op_def = _build_operation_def(aaf_file, operation, media_kind)
    datadef = aaf_file.dictionary.lookup_datadef(str(media_kind))

    # The OperationGroup output length is the duration the
    # clip occupies on the timeline.
    length = int(otio_clip.duration().value)
    operation_group = aaf_file.create.OperationGroup(op_def, length)
    operation_group.media_kind = media_kind
    operation_group["DataDefinition"].value = datadef

    for name, value in parameters.items():
        # AvidEffectID is carried as decoded metadata, not an AAF parameter.
        if name == "AvidEffectID":
            continue
        param_def = _parameter_def(aaf_file, name, operation)
        if param_def is None:
            continue
        if _is_keyframed(value):
            parameter = _build_varying_value(aaf_file, param_def, value)
        else:
            parameter = _build_constant_value(aaf_file, param_def, name, value)
        operation_group.parameters.append(parameter)

    # the length of the input_segment should be based on the duration
    # of the source (unretimed) media, not the retimed output length
    input_length = _input_segment_length(otio_clip)
    if input_length is not None:
        input_segment.length = input_length
    else:
        # throw an exception for now, probably represents a degenerate case
        # will add better error reporting if this actually comes up.
        raise Exception("Unable to determing segment length")

    operation_group.segments.append(input_segment)
    return operation_group


def _input_segment_length(otio_clip):
    try:
        available = otio_clip.available_range()
    except Exception:
        available = None
    if available is None:
        return None
    return int(available.duration.value)
